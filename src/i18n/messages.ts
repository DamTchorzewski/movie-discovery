type Plural = (n: number) => string;

function plural(locale: string, forms: Partial<Record<Intl.LDMLPluralRule, string>>): Plural {
  const rules = new Intl.PluralRules(locale);
  const format = new Intl.NumberFormat(locale);
  return (n) => {
    const form = forms[rules.select(n)] ?? forms.other ?? "";
    return form.replace("#", format.format(n));
  };
}

